const I18n = {
  /** Current language: "zh" | "en" */
  lang: localStorage.getItem('ch_lang') || 'zh',

  /**
   * Return translation string for a given key.
   * Falls back to key itself if not found.
   */
  t(key) {
    const dict = TRANSLATIONS[this.lang] || TRANSLATIONS['zh'];
    return dict[key] !== undefined ? dict[key] : key;
  },

  /**
   * Switch language, persist to localStorage, and re-render DOM.
   * @param {'zh'|'en'} lang
   */
  setLang(lang) {
    if (lang !== 'zh' && lang !== 'en') return;
    this.lang = lang;
    localStorage.setItem('ch_lang', lang);
    document.documentElement.lang = lang;
    this.apply();
    // Notify app to re-render current page if needed
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  },

  /**
   * Scan the DOM for data-i18n and data-i18n-placeholder attributes
   * and apply translations.
   */
  apply() {
    // Text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) el.textContent = val;
    });

    // Placeholder text
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val) el.placeholder = val;
    });

    // Title attribute
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = this.t(key);
      if (val) el.title = val;
    });

    // Page <title>
    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
      titleEl.textContent = this.t(titleEl.getAttribute('data-i18n'));
    }
  }
};
